// Release-signing helper (developer machine only; never shipped to users).
//   ReDotSignTool genkey <private.blob> <public_key.h>   create an ECDSA P-256 key pair (refuses to overwrite)
//   ReDotSignTool sign <private.blob> <file> <out.sig>    SHA-256 the file and write a 64-byte signature
//   ReDotSignTool sha256 <file>                           print the SHA-256
#include "core.h"
#include <cstdio>
#include <fstream>

using namespace rdu;

static bool readAll(const fs::path& p, std::vector<uint8_t>& out) {
    std::ifstream f(p, std::ios::binary); if (!f) return false;
    out.assign(std::istreambuf_iterator<char>(f), {}); return true;
}
static std::string hex(const std::vector<uint8_t>& v) { std::string s; char t[3]; for (auto b : v) { sprintf_s(t, "%02x", b); s += t; } return s; }

int wmain(int argc, wchar_t** argv) {
    if (argc >= 4 && std::wstring(argv[1]) == L"genkey") {
        fs::path priv = argv[2], header = argv[3];
        std::error_code ec;
        if (fs::exists(priv, ec)) { fprintf(stderr, "Refusing to overwrite an existing private key.\n"); return 2; }
        std::vector<uint8_t> pr, pu;
        if (!generateP256(pr, pu)) { fprintf(stderr, "Key generation failed.\n"); return 1; }
        fs::create_directories(priv.parent_path(), ec);
        { std::ofstream f(priv, std::ios::binary); f.write(reinterpret_cast<const char*>(pr.data()), static_cast<std::streamsize>(pr.size())); }
        std::ofstream h(header);
        h << "// Public ECDSA P-256 release-signing key (BCRYPT_ECCPUBLIC_BLOB). Generated by ReDotSignTool genkey.\n#pragma once\n#include <cstddef>\n#include <cstdint>\n"
             "inline const uint8_t kReleasePublicKey[] = {";
        for (size_t i = 0; i < pu.size(); ++i) { char t[8]; sprintf_s(t, "%s0x%02x", i ? "," : "", pu[i]); if (i % 16 == 0) h << "\n  "; h << t; }
        h << "\n};\ninline const size_t kReleasePublicKeySize = sizeof(kReleasePublicKey);\n";
        printf("Private key: %ls\nPublic key header: %ls\n", priv.c_str(), header.c_str());
        return 0;
    }
    if (argc >= 5 && std::wstring(argv[1]) == L"sign") {
        std::vector<uint8_t> priv, digest, sig; std::wstring err;
        if (!readAll(argv[2], priv)) { fprintf(stderr, "Cannot read the private key.\n"); return 1; }
        if (!sha256File(argv[3], digest, nullptr, err)) { fprintf(stderr, "%ls\n", err.c_str()); return 1; }
        if (!signDigest(priv, digest, sig)) { fprintf(stderr, "Signing failed.\n"); return 1; }
        std::ofstream f(fs::path(argv[4]), std::ios::binary); f.write(reinterpret_cast<const char*>(sig.data()), 64);
        printf("sha256=%s\nsignature written to %ls\n", hex(digest).c_str(), argv[4]);
        return 0;
    }
    if (argc >= 5 && std::wstring(argv[1]) == L"verify") {
        // verify <zip> <sig> <ReDotUpdater.exe>: use the public key actually embedded in the updater binary.
        std::vector<uint8_t> exe, sig, digest; std::wstring err;
        if (!readAll(argv[4], exe) || !readAll(argv[3], sig)) { fprintf(stderr, "Cannot read the updater or signature.\n"); return 1; }
        static const uint8_t magic[8] = {0x45, 0x43, 0x53, 0x31, 0x20, 0x00, 0x00, 0x00};   // BCRYPT_ECDSA_PUBLIC_P256_MAGIC + cbKey=32
        size_t at = 0, hits = 0, found = 0;
        for (size_t i = 0; i + 72 <= exe.size(); ++i) if (memcmp(&exe[i], magic, 8) == 0) { ++hits; found = i; }
        if (hits != 1) { fprintf(stderr, "Expected exactly one embedded public key in the updater, found %zu.\n", hits); return 1; }
        at = found;
        if (!sha256File(argv[2], digest, nullptr, err)) { fprintf(stderr, "%ls\n", err.c_str()); return 1; }
        bool sigOk = verifyP256(&exe[at], 72, digest, sig);
        printf("embedded key at offset %zu; signature %s; zip sha256=%s\n", at, sigOk ? "VALID" : "INVALID", hex(digest).c_str());
        ZipPackage pkg; bool zipOk = openZip(argv[2], pkg, err);
        printf("strict package validation: %s", zipOk ? "OK" : "FAILED");
        if (zipOk) printf(" (%zu entries, %.0f MB unpacked, container folder '%s')", pkg.entries.size(), static_cast<double>(pkg.totalSize) / 1048576.0, pkg.strippedRoot.c_str()); else printf(" - %ls", err.c_str());
        printf("\n");
        return sigOk && zipOk ? 0 : 1;
    }
    if (argc >= 3 && std::wstring(argv[1]) == L"sha256") {
        std::vector<uint8_t> digest; std::wstring err;
        if (!sha256File(argv[2], digest, nullptr, err)) { fprintf(stderr, "%ls\n", err.c_str()); return 1; }
        printf("%s\n", hex(digest).c_str()); return 0;
    }
    fprintf(stderr, "usage: ReDotSignTool genkey <private.blob> <public_key.h> | sign <private.blob> <file> <out.sig> | sha256 <file>\n");
    return 64;
}
